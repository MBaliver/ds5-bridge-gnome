// Generates generated/upstream-ipc.ts from the upstream companion source.
// Runs on every build, so new upstream channels are picked up automatically.
import fs from 'node:fs';
import path from 'node:path';
import { parseMainHandlers, parsePreloadChannels, repoRoot } from './upstream-ipc.mjs';

const handlers = parseMainHandlers();
const { channels, events } = parsePreloadChannels();
const version = JSON.parse(fs.readFileSync(path.join(repoRoot, 'companion', 'package.json'), 'utf8')).version;

const generic = Object.fromEntries(
  Object.entries(handlers).filter(([, h]) => h.kind === 'generic').map(([c, h]) => [c, h.method])
);
const custom = Object.keys(handlers).filter((c) => handlers[c].kind === 'custom').sort();

const out = `// GENERATED by scripts/gen-channels.mjs from companion/src -- do not edit.
export const UPSTREAM_VERSION = ${JSON.stringify(version)};
/** Every channel the upstream renderer (preload.ts) can invoke. */
export const INVOKE_CHANNELS: readonly string[] = ${JSON.stringify(channels, null, 2)};
/** Push channels the upstream renderer listens to. */
export const EVENT_CHANNELS: readonly string[] = ${JSON.stringify(events)};
/** Channels whose upstream handler only forwards to BridgeService.<method>. */
export const GENERIC_METHODS: Readonly<Record<string, string>> = ${JSON.stringify(generic, null, 2)};
/** Channels with custom upstream logic: implemented by hand (see upstream-ipc.lock.json). */
export const CUSTOM_CHANNELS: readonly string[] = ${JSON.stringify(custom, null, 2)};
`;
fs.mkdirSync(path.join(repoRoot, 'gnome', 'generated'), { recursive: true });
fs.writeFileSync(path.join(repoRoot, 'gnome', 'generated', 'upstream-ipc.ts'), out);
console.log(`upstream ${version}: ${channels.length} channels, ${Object.keys(generic).length} generic, ${custom.length} custom`);
